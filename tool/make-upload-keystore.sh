#!/usr/bin/env bash
#
# Creates the Play Store upload keystore and the android/key.properties file
# that android/app/build.gradle.kts reads.
#
# Run once, from the repository root:
#
#     tool/make-upload-keystore.sh
#
# The keystore is written OUTSIDE the repository (~/keystores by default) so it
# cannot be committed by accident. key.properties is written inside android/,
# where .gitignore already excludes it.
#
# BACK UP BOTH THE .jks FILE AND THE PASSWORDS. Losing them means you can never
# ship an update under the same Play listing without going through Google's
# key-reset process.

set -euo pipefail

KEYSTORE_DIR="${KEYSTORE_DIR:-$HOME/keystores}"
KEYSTORE="$KEYSTORE_DIR/slow-vibes-upload.jks"
ALIAS="upload"
PROPS="android/key.properties"

if [[ ! -f pubspec.yaml ]]; then
  echo "Run this from the repository root (no pubspec.yaml here)." >&2
  exit 1
fi

if ! command -v keytool >/dev/null 2>&1; then
  echo "keytool not found. Install a JDK 17 and put its bin/ on your PATH." >&2
  exit 1
fi

# Refuse to clobber. Overwriting a keystore that has already signed a released
# build is unrecoverable, so this is a hard stop rather than a prompt.
if [[ -f "$KEYSTORE" ]]; then
  echo "$KEYSTORE already exists — refusing to overwrite it." >&2
  echo "Delete it yourself if you are certain it has never signed a release." >&2
  exit 1
fi
if [[ -f "$PROPS" ]]; then
  echo "$PROPS already exists — refusing to overwrite it." >&2
  exit 1
fi

mkdir -p "$KEYSTORE_DIR"
chmod 700 "$KEYSTORE_DIR"

# Read the password here rather than letting keytool prompt, because the same
# value has to go into key.properties and the two must not drift apart.
read -rsp "Choose a keystore password (min 6 characters): " PASSWORD
echo
read -rsp "Repeat it: " PASSWORD_CONFIRM
echo

if [[ "$PASSWORD" != "$PASSWORD_CONFIRM" ]]; then
  echo "Passwords do not match." >&2
  exit 1
fi
if [[ ${#PASSWORD} -lt 6 ]]; then
  echo "keytool requires at least 6 characters." >&2
  exit 1
fi

# Under Git Bash on Windows, $HOME expands to a POSIX path like
# /c/Users/name. Gradle runs on the JVM and cannot open that — it needs
# C:/Users/name. cygpath -m converts it, and uses forward slashes, which also
# sidesteps .properties backslash escaping. Absent everywhere else, so the
# plain path is used on Linux and macOS.
if command -v cygpath >/dev/null 2>&1; then
  STORE_PATH="$(cygpath -m "$KEYSTORE")"
else
  STORE_PATH="$KEYSTORE"
fi

echo
echo "Creating $STORE_PATH"
echo "You will be asked for a name and location; they appear only in the"
echo "certificate and are not shown to users. Your own name is fine."
echo "keytool will warn that JKS is a proprietary format — ignore it. JKS is"
echo "what Flutter's own signing instructions use and what Gradle expects here."
echo

# -storepass/-keypass are passed via stdin-free flags rather than typed at the
# prompt so the same string reaches both the keystore and key.properties.
keytool -genkeypair -v \
  -keystore "$STORE_PATH" \
  -storetype JKS \
  -storepass "$PASSWORD" \
  -keypass "$PASSWORD" \
  -alias "$ALIAS" \
  -keyalg RSA \
  -keysize 2048 \
  -validity 10000

chmod 600 "$KEYSTORE"

# Java .properties treats backslashes as escapes, so a password containing one
# would be silently mangled and the build would fail with a wrong-password
# error that points nowhere useful.
escape_property() {
  printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/:/\\:/g' -e 's/=/\\=/g'
}

{
  echo "# Generated by tool/make-upload-keystore.sh — never commit this file."
  echo "storeFile=$(escape_property "$STORE_PATH")"
  echo "storePassword=$(escape_property "$PASSWORD")"
  echo "keyAlias=$ALIAS"
  echo "keyPassword=$(escape_property "$PASSWORD")"
} > "$PROPS"

chmod 600 "$PROPS"

echo
echo "Wrote $PROPS"
echo
echo "Next:"
echo "  1. Back up $STORE_PATH and its password somewhere durable."
echo "  2. flutter build appbundle --release"
echo "  3. Confirm it used this key, not the debug key:"
echo "       keytool -printcert -jarfile build/app/outputs/bundle/release/app-release.aab"
echo "     The owner must be the name you just typed, NOT 'CN=Android Debug'."
